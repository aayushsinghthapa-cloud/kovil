#define NGLYPHS ((int)(sizeof font / sizeof font[0]))

static const uint8_t *glyph_rows(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    for (int i = 0; i < NGLYPHS; i++)
        if (font[i].ch == c)
            return font[i].rows;
    return NULL; /* unknown (and space) draw as blank */
}

int text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n])
        n++;
    return n * 6 * scale - scale; /* 5px glyph + 1px gap */
}

void text_draw(Framebuffer *fb, int x, int y, int scale,
               uint32_t color, const char *s)
{
    for (; *s; s++, x += 6 * scale) {
        const uint8_t *rows = glyph_rows(*s);
        if (!rows)
            continue;
        for (int r = 0; r < 7; r++)
            for (int c = 0; c < 5; c++)
                if (rows[r] & (0x10 >> c))
                    fb_fill_rect(fb, x + c * scale, y + r * scale,
                                 scale, scale, color);
    }
}

void text_draw_shadow(Framebuffer *fb, int x, int y, int scale,
                      uint32_t color, const char *s)
{
    text_draw(fb, x + scale, y + scale, scale, COLOR_RGB(20, 16, 14), s);
    text_draw(fb, x, y, scale, color, s);
}
